/** Indicatifs uniques, du plus long au plus court (analyse d'un numéro). */
function phone_dial_codes(): array
{
    static $codes = null;
    if ($codes === null) {
        $codes = array_values(array_unique(array_column(phone_countries(), 'dial')));
        usort($codes, static fn(string $a, string $b): int => strlen($b) <=> strlen($a));
    }
    return $codes;
}

/** Indicatif d'un pays (ISO) ; '' si le code est inconnu. */
function phone_dial_for(string $code): string
{
    if ($code === '') {
        return '';
    }
    foreach (phone_countries() as $c) {
        if ($c['code'] === $code) {
            return $c['dial'];
        }
    }
    return '';
}
